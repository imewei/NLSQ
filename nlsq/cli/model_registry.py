"""Model registry for NLSQ CLI.

This module provides model function resolution for curve fitting workflows:
- Builtin models from nlsq.functions module
- Custom models loaded from external Python files
- Polynomial models generated by degree

The ModelRegistry class handles discovery, loading, and validation of
model functions for use in curve fitting workflows.

Security Features
-----------------
Custom models are validated before loading to prevent arbitrary code execution:
- AST-based pattern detection for dangerous operations
- Path traversal prevention
- Resource limits (timeout, memory) for model execution
- Audit logging for model loading attempts

Example Usage
-------------
>>> from nlsq.cli.model_registry import ModelRegistry
>>>
>>> registry = ModelRegistry()
>>>
>>> # Get a builtin model
>>> linear = registry.get_model("linear", {"type": "builtin", "name": "linear"})
>>>
>>> # Get a custom model from file (with security validation)
>>> custom = registry.get_model(
...     "/path/to/model.py",
...     {"type": "custom", "path": "/path/to/model.py", "function": "my_model"}
... )
>>>
>>> # Get a polynomial model
>>> poly3 = registry.get_model("poly", {"type": "polynomial", "degree": 3})
"""

import difflib
import functools
import inspect
import logging
import types
import uuid
from collections.abc import Callable
from pathlib import Path
from typing import Any

import numpy as np

from nlsq.cli.errors import ModelError, cfg_get
from nlsq.cli.model_validation import (
    get_audit_logger,
    resource_limits,
    strict_models_enabled,
    validate_model,
    validate_path,
)

logger = logging.getLogger("nlsq.cli.model_registry")

# Type alias for model functions
ModelFunction = Callable[..., Any]


def fit_param_range(model: Any) -> tuple[int, int] | None:
    """(required, total) fit-parameter counts of ``f(x, *params)``.

    Only positional parameters after ``x`` count; defaulted ones may be omitted
    (curve_fit sizes the fit from p0). None for ``*args`` models or when the
    signature cannot be inspected.
    """
    try:
        params = list(inspect.signature(model).parameters.values())
    except (TypeError, ValueError):
        return None
    if any(p.kind == p.VAR_POSITIONAL for p in params):
        return None
    positional = [
        p for p in params if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)
    ]
    if not positional:  # no x parameter: nothing to check against
        return None
    positional = positional[1:]
    required = sum(p.default is p.empty for p in positional)
    return required, len(positional)


def _describe_range(n_range: tuple[int, int]) -> str:
    lo, hi = n_range
    return str(hi) if lo == hi else f"{lo} to {hi}"


class ModelRegistry:
    """Registry for model functions used in curve fitting.

    The ModelRegistry handles three types of models:
    1. **Builtin**: Models from nlsq.functions (linear, gaussian, etc.)
    2. **Custom**: Models loaded from external Python files
    3. **Polynomial**: Dynamically generated polynomial functions

    Each model function may have optional methods attached:
    - `estimate_p0(xdata, ydata)`: Estimate initial parameters
    - `bounds()`: Return default parameter bounds

    Attributes
    ----------
    _builtin_cache : dict
        Cache of loaded builtin model functions.

    Examples
    --------
    >>> registry = ModelRegistry()
    >>> model = registry.get_model("gaussian", {"type": "builtin", "name": "gaussian"})
    >>> print(model.estimate_p0([1,2,3], [1,4,9]))
    """

    def __init__(self) -> None:
        """Initialize ModelRegistry."""
        self._builtin_cache: dict[str, ModelFunction] = {}
        # Extra roots a custom model file may live under besides the CWD
        # (e.g. the workflow YAML's directory); `../` escapes stay rejected.
        self.allowed_model_dirs: list[Path] = []

    def list_builtin_models(self) -> list[str]:
        """List all available builtin model names.

        Discovers models by introspecting nlsq.functions.__all__.

        Returns
        -------
        list[str]
            Names of available builtin models.

        Examples
        --------
        >>> registry = ModelRegistry()
        >>> models = registry.list_builtin_models()
        >>> print("linear" in models)
        True
        """
        import nlsq.core.functions

        return list(nlsq.core.functions.__all__)

    def get_model(self, name_or_path: str, config: dict[str, Any]) -> ModelFunction:
        """Get a model function by name or path.

        Parameters
        ----------
        name_or_path : str
            For builtin models: the model name (e.g., "linear", "gaussian").
            For custom models: path to the Python file.
            For polynomial: any identifier (degree is in config).
        config : dict
            Model configuration with keys:
            - type: str - Model type ("builtin", "custom", "polynomial")
            - name: str - Model name (for builtin)
            - path: str - File path (for custom)
            - function: str - Function name (for custom)
            - degree: int - Polynomial degree (for polynomial)

        Returns
        -------
        ModelFunction
            The model function with optional estimate_p0 and bounds methods.

        Raises
        ------
        ModelError
            If the model cannot be resolved.

        Examples
        --------
        >>> registry = ModelRegistry()
        >>> # Builtin model
        >>> linear = registry.get_model("linear", {"type": "builtin", "name": "linear"})
        >>> # Custom model
        >>> custom = registry.get_model(
        ...     "path/model.py",
        ...     {"type": "custom", "path": "path/model.py", "function": "my_func"}
        ... )
        >>> # Polynomial model
        >>> poly = registry.get_model("poly", {"type": "polynomial", "degree": 2})
        """
        model_type = cfg_get(config, "type", "builtin")

        if model_type == "builtin":
            return self._get_builtin_model(config)
        if model_type == "custom":
            return self._get_custom_model(config)
        if model_type == "polynomial":
            return self._get_polynomial_model(config)
        raise ModelError(
            f"Unknown model type: {model_type!r}",
            model_type=model_type,
            context={"valid_types": ["builtin", "custom", "polynomial"]},
            suggestion="Use type 'builtin', 'custom', or 'polynomial'",
        )

    def _get_builtin_model(self, config: dict[str, Any]) -> ModelFunction:
        """Get a builtin model from nlsq.functions.

        Parameters
        ----------
        config : dict
            Configuration with 'name' key specifying the model name.

        Returns
        -------
        ModelFunction
            The builtin model function.

        Raises
        ------
        ModelError
            If the model name is not found in nlsq.functions.
        """
        model_name = cfg_get(config, "name", "")

        if not model_name:
            raise ModelError(
                "Model name is required for builtin models",
                model_type="builtin",
                suggestion="Specify 'name' in the model configuration",
            )

        # Check cache first
        if model_name in self._builtin_cache:
            return self._builtin_cache[model_name]

        # Get available models
        available = self.list_builtin_models()

        if model_name not in available:
            # Try to suggest a similar model name
            suggestion = self._suggest_similar_model(model_name, available)
            raise ModelError(
                f"Builtin model '{model_name}' not found",
                model_name=model_name,
                model_type="builtin",
                context={"available_models": available},
                suggestion=suggestion,
            )

        # 'polynomial' is a factory, not a model: build it from config['degree']
        if model_name == "polynomial":
            return self._get_polynomial_model(config)

        import nlsq.core.functions

        model = getattr(nlsq.core.functions, model_name)

        # Cache and return
        self._builtin_cache[model_name] = model
        return model

    # =========================================================================
    # Custom Model Helper Methods (extracted for complexity reduction)
    # =========================================================================

    def _validate_custom_model_config(
        self,
        config: dict[str, Any],
    ) -> tuple[str, str]:
        """Validate and extract custom model configuration.

        Parameters
        ----------
        config : dict
            Configuration with path, function, and optional trusted keys.

        Returns
        -------
        file_path : str
            The file path to the model.
        function_name : str
            The function name to load.

        Raises
        ------
        ModelError
            If file_path or function_name is missing.
        """
        file_path = cfg_get(config, "path", "")
        function_name = cfg_get(config, "function", "")

        if not file_path:
            raise ModelError(
                "File path is required for custom models",
                model_type="custom",
                suggestion="Specify 'path' in the model configuration",
            )

        if not function_name:
            raise ModelError(
                "Function name is required for custom models",
                model_type="custom",
                context={"path": file_path},
                suggestion="Specify 'function' in the model configuration",
            )

        return file_path, function_name

    def _validate_model_file_exists(
        self,
        file_path: str,
        function_name: str,
    ) -> Path:
        """Validate that the model file exists and is a regular file.

        Parameters
        ----------
        file_path : str
            Path to the model file.
        function_name : str
            Function name (for error messages).

        Returns
        -------
        path : Path
            Validated Path object.

        Raises
        ------
        ModelError
            If file doesn't exist or isn't a regular file.
        """
        path = Path(file_path)
        if not path.exists():
            raise ModelError(
                f"Custom model file not found: {file_path}",
                model_name=function_name,
                model_type="custom",
                context={"path": file_path},
                suggestion="Check the file path and ensure the file exists",
            )

        if not path.is_file():
            raise ModelError(
                f"Path is not a file: {file_path}",
                model_name=function_name,
                model_type="custom",
                context={"path": file_path},
                suggestion="Provide a path to a Python file",
            )

        return path

    def _check_path_security(
        self,
        path: Path,
        function_name: str,
        is_trusted: bool,
    ) -> None:
        """Check for path traversal attacks.

        Parameters
        ----------
        path : Path
            Path to validate.
        function_name : str
            Function name (for error messages).
        is_trusted : bool
            Whether the model is trusted.

        Raises
        ------
        ModelError
            If path traversal is detected.
        """
        if not any(
            validate_path(path, base) for base in (None, *self.allowed_model_dirs)
        ):
            audit_logger = get_audit_logger()
            from nlsq.cli.model_validation import ModelValidationResult

            result = ModelValidationResult(
                path=path,
                is_valid=False,
                is_trusted=is_trusted,
                violations=["Path traversal detected"],
            )
            audit_logger.log_load_attempt(path, result)
            raise ModelError(
                f"Path traversal detected: {path}",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path)},
                suggestion="Model files must be within the current working directory "
                "or the directory of the workflow file",
            )

    def _validate_model_security(
        self,
        path: Path,
        function_name: str,
        is_trusted: bool,
        source: bytes | None = None,
        strict: bool = False,
    ) -> None:
        """Run AST-based security validation on the model file.

        Parameters
        ----------
        path : Path
            Path to the model file.
        function_name : str
            Function name (for error messages).
        is_trusted : bool
            Whether to skip validation.
        source : bytes, optional
            Exact file bytes to validate (the same bytes that get executed).
        strict : bool, default=False
            Enforce the opt-in strict allowlist in addition to the denylist.

        Raises
        ------
        ModelError
            If security validation fails and not trusted.
        """
        validation_result = validate_model(
            path, trusted=is_trusted, source=source, strict=strict
        )
        if strict and is_trusted:
            logger.warning(
                "Model %s: trusted=true bypasses the strict allowlist (strict "
                "mode was requested). Violations that would have blocked: %s",
                path,
                "; ".join(validation_result.violations[:3]) or "none",
            )

        audit_logger = get_audit_logger()
        audit_logger.log_load_attempt(path, validation_result)

        if not validation_result.is_valid and not is_trusted:
            violations_msg = "; ".join(validation_result.violations[:3])
            if len(validation_result.violations) > 3:
                violations_msg += f" (and {len(validation_result.violations) - 3} more)"

            raise ModelError(
                f"Security validation failed for {path}: {violations_msg}",
                model_name=function_name,
                model_type="custom",
                context={
                    "path": str(path),
                    "violations": validation_result.violations,
                },
                suggestion=(
                    "Remove dangerous patterns, or set `trusted: true` in the "
                    "YAML config's `model:` block to skip validation"
                    + (
                        " (strict allowlist mode is on: only the documented "
                        "module allowlist is permitted)"
                        if strict
                        else ""
                    )
                ),
            )

        if is_trusted and validation_result.violations:
            logger.warning(
                "Loading model %s with trusted=true, bypassing security checks. "
                "Violations that would have blocked: %s",
                path,
                "; ".join(validation_result.violations[:3]),
            )

    def _load_module_from_path(
        self,
        path: Path,
        function_name: str,
        source: bytes,
    ) -> Any:
        """Load a Python module from a file path.

        Parameters
        ----------
        path : Path
            Path to the Python file.
        function_name : str
            Function name (for error messages).
        source : bytes
            Exact file bytes that were security-validated. These are compiled
            directly (not re-read from disk, and no ``__pycache__`` .pyc is
            consulted), so validated code == executed code.

        Returns
        -------
        module : module
            The loaded Python module.

        Raises
        ------
        ModelError
            If module cannot be loaded.
        """
        try:
            # A unique module name per load (not a fixed literal) avoids any
            # risk of import-machinery identity collisions between two
            # custom models loaded in the same process (e.g. sys.modules
            # keyed by name, coverage/tracer bookkeeping keyed by module).
            module_name = f"nlsq_custom_model_{uuid.uuid4().hex}"
            module = types.ModuleType(module_name)
            module.__file__ = str(path)
            code = compile(source, str(path), "exec")
            with resource_limits():
                # Intentional: runs the exact bytes validate_model() approved.
                exec(code, module.__dict__)  # nosec B102
            return module
        except SyntaxError as e:
            raise ModelError(
                f"Syntax error in custom model file: {e}",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path), "line": e.lineno},
                suggestion="Fix the syntax error in the custom model file",
            ) from e
        except ModelError:
            raise
        except Exception as e:
            raise ModelError(
                f"Error loading custom model file: {e}",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path)},
                suggestion="Ensure the file is a valid Python module",
            ) from e

    def _resolve_function_from_module(
        self,
        module: Any,
        function_name: str,
        path: Path,
    ) -> ModelFunction:
        """Resolve and validate the model function from a loaded module.

        Parameters
        ----------
        module : module
            The loaded Python module.
        function_name : str
            Name of the function to extract.
        path : Path
            Path to the module file (for error messages).

        Returns
        -------
        model : ModelFunction
            The resolved model function.

        Raises
        ------
        ModelError
            If function not found, not callable, or invalid signature.
        """
        if not hasattr(module, function_name):
            available_functions = [
                name
                for name, obj in inspect.getmembers(module)
                if callable(obj) and not name.startswith("_")
            ]
            raise ModelError(
                f"Function '{function_name}' not found in {path}",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path), "available_functions": available_functions},
                suggestion=f"Available functions: {', '.join(available_functions) or 'none'}",
            )

        model = getattr(module, function_name)

        if not callable(model):
            raise ModelError(
                f"'{function_name}' is not a callable function",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path)},
                suggestion="Ensure the model is defined as a function",
            )

        # Validate signature has at least one parameter (x)
        sig = inspect.signature(model)
        params = list(sig.parameters.keys())
        if len(params) < 1:
            raise ModelError(
                f"Model function '{function_name}' must have at least one parameter (x)",
                model_name=function_name,
                model_type="custom",
                context={"path": str(path), "parameters": params},
                suggestion="Define model as f(x, *params) where x is the independent variable",
            )

        return model

    def _attach_model_utilities(
        self,
        model: ModelFunction,
        module: Any,
    ) -> ModelFunction:
        """Attach estimate_p0 and bounds methods from module to model.

        Resolution order: ``estimate_<fn>_p0`` / ``<fn>_bounds``, then bare
        ``estimate_p0`` / ``bounds`` only for the first model defined in the
        module.

        Parameters
        ----------
        model : ModelFunction
            The model function.
        module : module
            The module containing optional utilities.

        Returns
        -------
        model : ModelFunction
            The model with attached utilities.
        """
        # Per-function helpers win: ``estimate_<fn>_p0`` / ``<fn>_bounds``.
        # Bare ``estimate_p0`` / ``bounds`` belong to the FIRST model function
        # defined in the module (the template's convention); applying them to
        # any other model would silently use another model's p0/bounds.
        if getattr(model, "__module__", None) != module.__name__:
            # A re-exported function (`from nlsq.core.functions import gaussian`)
            # is shared: setting attributes on it would leak into every user.
            return model
        name = getattr(model, "__name__", "")
        fn_p0 = getattr(module, f"estimate_{name}_p0", None) or getattr(
            module, f"{name}_estimate_p0", None
        )
        fn_bounds = getattr(module, f"{name}_bounds", None)
        fn_names = getattr(module, f"{name}_parameter_names", None)

        def has_fit_parameters(function: Any) -> bool:
            """Require positional x plus positional or variadic fit parameters."""
            parameters = inspect.signature(function).parameters.values()
            positional = sum(
                p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)
                for p in parameters
            )
            variadic = any(p.kind == p.VAR_POSITIONAL for p in parameters)
            return positional >= 2 or (positional >= 1 and variadic)

        models = sorted(
            (
                f
                for n, f in vars(module).items()
                if inspect.isfunction(f)
                and f.__module__ == module.__name__
                and n not in ("estimate_p0", "bounds", "parameter_names")
                and not n.startswith(("_", "estimate_"))
                and not n.endswith(("_bounds", "_p0", "_parameter_names"))
                and has_fit_parameters(f)
            ),
            key=lambda f: f.__code__.co_firstlineno,
        )
        owns_bare = not models or models[0] is model

        if not callable(fn_p0) and owns_bare:
            fn_p0 = getattr(module, "estimate_p0", None)
        if not callable(fn_bounds) and owns_bare:
            fn_bounds = getattr(module, "bounds", None)
        if not callable(fn_names) and owns_bare:
            fn_names = getattr(module, "parameter_names", None)

        # Never hand the optimiser a p0/bounds sized for a different model.
        n_range = fit_param_range(model)

        def checked(function: Any, what: str, size: Any) -> Any:
            @functools.wraps(function)
            def wrapper(*args: Any, **kwargs: Any) -> Any:
                value = function(*args, **kwargs)
                if value is None:  # "no p0/bounds": let the caller fall back
                    return value
                n = size(value)
                if (
                    n_range is not None
                    and not n_range[0] <= n <= n_range[1]
                    and not (
                        what == "bounds" and n == 1  # scalar bound broadcasts
                    )
                ):
                    raise ValueError(
                        f"{function.__name__}() returned {what} of length {n}, but "
                        f"model '{name}' takes {_describe_range(n_range)} "
                        "parameter(s)"
                    )
                return value

            return wrapper

        if callable(fn_p0):
            model.estimate_p0 = checked(fn_p0, "p0", len)  # type: ignore[attr-defined]
        if callable(fn_names):  # length is validated by the runner
            model.parameter_names = fn_names  # type: ignore[attr-defined]
        if callable(fn_bounds):
            model.bounds = checked(  # type: ignore[attr-defined]
                fn_bounds, "bounds", lambda b: np.size(b[0])
            )

        return model

    def _get_custom_model(
        self,
        config: dict[str, Any],
        *,
        trusted: bool = False,
    ) -> ModelFunction:
        """Load a custom model from an external Python file.

        Parameters
        ----------
        config : dict
            Configuration with:
            - path: str - Path to the Python file
            - function: str - Name of the model function
            - trusted: bool - Skip security validation (default: False)
            - strict: bool - Enforce the opt-in strict allowlist (default:
              False; ``NLSQ_STRICT_MODELS=1`` turns it on globally)
        trusted : bool, default=False
            If True, skip security validation. This is a keyword-only
            argument that overrides config["trusted"].

        Returns
        -------
        ModelFunction
            The custom model function with optional estimate_p0 and bounds.

        Raises
        ------
        ModelError
            If the file or function cannot be found, the function is invalid,
            or the model fails security validation.
        """
        # Step 1: Validate configuration
        file_path, function_name = self._validate_custom_model_config(config)
        config_trusted = config.get("trusted", False)
        if not isinstance(config_trusted, bool):
            # YAML `trusted: "false"` is a truthy string and would silently
            # skip validation; only a real boolean may set the flag.
            raise ModelError(
                f"'trusted' must be true or false, got {config_trusted!r}",
                model_type="custom",
                suggestion="Use an unquoted YAML boolean: `trusted: true`.",
            )
        is_trusted = trusted or config_trusted
        config_strict = config.get("strict", False)
        if not isinstance(config_strict, bool):
            raise ModelError(
                f"'strict' must be true or false, got {config_strict!r}",
                model_type="custom",
                suggestion="Use an unquoted YAML boolean: `strict: true`.",
            )
        is_strict = config_strict or strict_models_enabled()

        # Step 2: Validate file exists
        path = self._validate_model_file_exists(file_path, function_name)

        # Step 3: Security validation - path traversal
        self._check_path_security(path, function_name, is_trusted)

        # Read once: the validated bytes are the executed bytes.
        source = path.read_bytes()

        # Step 4: Security validation - AST-based
        self._validate_model_security(
            path, function_name, is_trusted, source, strict=is_strict
        )

        # Step 5: Load module dynamically
        module = self._load_module_from_path(path, function_name, source)

        # Step 6: Resolve and validate function
        model = self._resolve_function_from_module(module, function_name, path)

        # Step 7: Attach utility methods
        return self._attach_model_utilities(model, module)

    def _get_polynomial_model(self, config: dict[str, Any]) -> ModelFunction:
        """Generate a polynomial model of given degree.

        Parameters
        ----------
        config : dict
            Configuration with 'degree' key specifying the polynomial degree.

        Returns
        -------
        ModelFunction
            A polynomial function with estimate_p0 and bounds methods.

        Raises
        ------
        ModelError
            If the degree is invalid.
        """
        degree = config.get("degree")

        if degree is None:
            raise ModelError(
                "Polynomial degree is required",
                model_type="polynomial",
                suggestion="Specify 'degree' in the model configuration",
            )

        try:
            # int() would silently truncate 2.9 -> 2 and True -> 1
            if isinstance(degree, bool) or (
                isinstance(degree, float) and not degree.is_integer()
            ):
                raise ValueError(degree)
            degree = int(degree)
        except (ValueError, TypeError) as e:
            raise ModelError(
                f"Invalid polynomial degree: {degree!r}",
                model_type="polynomial",
                context={"degree": degree},
                suggestion="Degree must be a non-negative integer",
            ) from e

        if degree < 0:
            raise ModelError(
                f"Polynomial degree must be non-negative, got {degree}",
                model_type="polynomial",
                context={"degree": degree},
                suggestion="Use a non-negative integer for degree (0, 1, 2, ...)",
            )

        # Use nlsq.core.functions.polynomial factory
        import nlsq.core.functions

        model = nlsq.core.functions.polynomial(degree)

        return model

    def _suggest_similar_model(self, name: str, available: list[str]) -> str:
        """Suggest a similar model name based on fuzzy matching.

        Parameters
        ----------
        name : str
            The invalid model name.
        available : list[str]
            List of available model names.

        Returns
        -------
        str
            A suggestion message.
        """
        suggestions = difflib.get_close_matches(name, available, cutoff=0.5)

        if suggestions:
            return f"Did you mean: {', '.join(suggestions)}?"
        return f"Available models: {', '.join(available)}"
