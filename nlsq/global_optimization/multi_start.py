def _fit_single_start(
    f: Callable,
    xdata: np.ndarray,
    ydata: np.ndarray,
    p0: np.ndarray,
    bounds: tuple,
    kwargs: dict,
    curve_fit_kwargs: dict | None = None,
) -> tuple[np.ndarray, float, Any]:
    """Thread worker -- isolated CurveFit instance per call.

    Each worker creates its own CurveFit() to isolate mutable per-fit state
    in LeastSquares (self.n, self.func_*, self.jac*). JIT-compiled functions
    and the compilation cache are shared safely across threads.

    Parameters
    ----------
    f : Callable
        Model function ``f(x, *params) -> y``.
    xdata : np.ndarray
        Independent variable data.
    ydata : np.ndarray
        Dependent variable data.
    p0 : np.ndarray
        Initial parameter guess for this starting point.
    bounds : tuple
        Parameter bounds (lower, upper).
    kwargs : dict
        Additional arguments passed to curve_fit.
    curve_fit_kwargs : dict, optional
        Constructor kwargs mirroring the orchestrator's ``curve_fit``
        instance (flength, enable_stability, etc.), so a custom instance
        passed to ``MultiStartOrchestrator`` actually takes effect.

    Returns
    -------
    tuple
        (params, loss, result) where params is the fitted parameters,
        loss is the sum of squared residuals (inf on failure), and
        result is the CurveFitResult or None on failure.
    """
    from nlsq.core.minpack import CurveFit

    try:
        cf = CurveFit(**(curve_fit_kwargs or {}))
        result: CurveFitResult = cf.curve_fit(  # type: ignore[assignment]
            f,
            xdata,
            ydata,
            p0=p0,
            bounds=bounds,
            **kwargs,
        )
        if hasattr(result, "cost"):
            loss = 2 * result.cost  # cost is half sum of squares
        elif hasattr(result, "fun"):
            loss = float(np.sum(np.asarray(result.fun) ** 2))
        else:
            # Fallback: compute from residuals
            predictions = f(xdata, *result.popt)
            loss = float(np.sum((ydata - np.asarray(predictions)) ** 2))
        # NaN must not be able to sort ahead of a genuinely successful,
        # finite-loss fit -- coerce any non-finite loss (NaN included) to
        # +inf so it always sorts last and is excluded from n_successful.
        # A NaN cost specifically (as opposed to an ordinary large-but-finite
        # cost) usually signals numerical blowup/divergence at this starting
        # point, worth a distinct log line for diagnosability.
        if not np.isfinite(loss):
            _worker_logger.debug(
                "Starting point %s produced non-finite loss (%s); coercing to inf",
                p0,
                loss,
            )
            loss = float("inf")
        return (result.popt, loss, result)
    except Exception as e:
        _worker_logger.debug("Starting point failed: %s", e, exc_info=True)
        return (p0, float("inf"), None)


# Hide the N-1 losing starts' non-convergence noise, but let a typo'd-kwarg warning through
_IGNORE_MSG = r"(?!Ignoring unknown keyword)"
_IGNORE_ENTRY = (
    "ignore",
    re.compile(_IGNORE_MSG, re.IGNORECASE),
    OptimizeWarning,
    None,
    0,
)
_ignore_lock = threading.Lock()
_ignore_state = {"depth": 0, "added": False}


def _context_aware_warnings() -> bool:
    # Worker threads only see the caller's catch_warnings() context when they
    # also inherit the context (thread_inherit_context; off on GIL builds by default).
    return bool(getattr(sys.flags, "context_aware_warnings", False)) and bool(
        getattr(sys.flags, "thread_inherit_context", False)
    )


@contextmanager
def _suppress_optimize_warning() -> Iterator[None]:
    """Ignore ``OptimizeWarning`` process-wide while any caller is inside.

    ``warnings.catch_warnings`` saves/restores the whole global filter list and
    is not thread-safe: overlapping users restore each other's stale snapshot and
    leave the ignore filter installed forever. Here the filter is added on the
    0 -> 1 transition and removed on 1 -> 0 (only if this helper added it), under
    a lock. Limit: while one multi-start runs, other threads' OptimizeWarnings
    are hidden too (shortcut: needs a per-thread flag at the emit site).
    """
    if _context_aware_warnings():
        # Context-aware warnings: filters are per-context, so catch_warnings is
        # already thread/task-safe and a global filter edit would hit the wrong list.
        with warnings.catch_warnings():
            warnings.filterwarnings(
                "ignore", message=_IGNORE_MSG, category=OptimizeWarning
            )
            yield
        return
    with _ignore_lock:
        if _ignore_state["depth"] == 0:
            _ignore_state["added"] = _IGNORE_ENTRY not in warnings.filters
            if _ignore_state["added"]:
                warnings.filterwarnings(
                    "ignore", message=_IGNORE_MSG, category=OptimizeWarning
                )
        _ignore_state["depth"] += 1
    try:
        yield
    finally:
        with _ignore_lock:
            _ignore_state["depth"] -= 1
            if _ignore_state["depth"] == 0 and _ignore_state["added"]:
                if _IGNORE_ENTRY in warnings.filters:
                    warnings.filters.remove(_IGNORE_ENTRY)  # type: ignore[attr-defined]  # runtime list
                    mutated = getattr(warnings, "_filters_mutated", None)
                    if mutated is not None:
                        mutated()
                _ignore_state["added"] = False


# Thread ident -> buffer of that thread's start-fit WARNING records (see below).
_quiet_threads: dict[int, list[logging.LogRecord]] = {}


class _DeferStartWarnings(logging.Filter):
    """Drop a running start's nlsq WARNING records and buffer them for replay.

    Per-start logger warnings (e.g. "Jacobian is rank-deficient") would read as
    warnings about the returned winner; only the winner's are replayed (marked
    ``_nlsq_replay`` so this filter lets them through).
    """

    def filter(self, record: logging.LogRecord) -> bool:
        if getattr(record, "_nlsq_replay", False):
            return True
        buf = _quiet_threads.get(record.thread)  # type: ignore[arg-type]
        if buf is not None and record.levelno == logging.WARNING:
            buf.append(record)
            return False
        return True


_defer_filter = _DeferStartWarnings()


def _install_defer_filter() -> None:
    # Logger filters only see records created on that logger, so attach to each
    # existing nlsq.* logger (addFilter is idempotent; no-op when no start runs).
    # shortcut: loggers first created during a start are not covered; upgrade to a
    # LogRecord factory if one appears.
    for name, lg in list(logging.root.manager.loggerDict.items()):
        if name.startswith("nlsq") and isinstance(lg, logging.Logger):
            lg.addFilter(_defer_filter)


def _fit_start_quietly(buf: list[logging.LogRecord], *args: Any) -> tuple:
    ident = threading.get_ident()
    prev = _quiet_threads.get(ident)
    _quiet_threads[ident] = buf
    try:
        return _fit_single_start(*args)
    finally:
        if prev is None:
            _quiet_threads.pop(ident, None)
        else:
            _quiet_threads[ident] = prev


def _select_worker_count(n_starts: int) -> int:
    """Select optimal number of parallel workers.

    Adapts to hardware:
    - Multi-GPU: one fit per GPU
    - Single GPU: min(n_starts, 4) to limit memory contention
    - CPU-only: min(n_starts, cpu_count, 16) to prevent XLA oversubscription

    Parameters
    ----------
    n_starts : int
        Number of starting points to evaluate.

    Returns
    -------
    int
        Number of workers to use for parallel evaluation.
    """
    n_devices = len(jax.devices())
    if n_devices > 1:
        return min(n_starts, n_devices)
    if n_devices == 1:
        return min(n_starts, 4)
    return min(n_starts, os.cpu_count() or 4, 16)


class MultiStartOrchestrator:
    """Orchestrator for multi-start optimization with LHS sampling.

    This class generates multiple starting points using Latin Hypercube Sampling
    (or other quasi-random samplers), evaluates each starting point by running
    a full optimization, and selects the best result based on minimum loss.

    Parameters
    ----------
    config : GlobalOptimizationConfig, optional
        Configuration for multi-start optimization. If None, uses default config.
    curve_fit_instance : CurveFit, optional
        Custom CurveFit instance to use for optimization. If None, creates a new one.

    Attributes
    ----------
    config : GlobalOptimizationConfig
        Configuration settings for multi-start optimization.
    curve_fit : CurveFit
        CurveFit instance used for running optimizations.
    logger : NLSQLogger
        Logger for multi-start operations.

    Examples
    --------
    >>> from nlsq.global_optimization import MultiStartOrchestrator, GlobalOptimizationConfig
    >>>
    >>> # Basic usage
    >>> orchestrator = MultiStartOrchestrator()
    >>> result = orchestrator.fit(model, x, y, bounds=([0, 0], [10, 10]))
    >>>
    >>> # With custom config
    >>> config = GlobalOptimizationConfig(n_starts=20, sampler='sobol')
    >>> orchestrator = MultiStartOrchestrator(config=config)
    >>>
    >>> # Using presets
    >>> orchestrator = MultiStartOrchestrator.from_preset('global')
    """

    def __init__(
        self,
        config: GlobalOptimizationConfig | None = None,
        curve_fit_instance: "CurveFit | None" = None,
    ):
        """Initialize MultiStartOrchestrator.

        Parameters
        ----------
        config : GlobalOptimizationConfig, optional
            Configuration for multi-start optimization.
        curve_fit_instance : CurveFit, optional
            Custom CurveFit instance for optimization.
        """
        self.config = config if config is not None else GlobalOptimizationConfig()
        if curve_fit_instance is not None:
            self.curve_fit = curve_fit_instance
        else:
            # Deferred import to avoid circular dependency
            from nlsq.core.minpack import CurveFit

            self.curve_fit = CurveFit()
        self.logger = get_logger("multi_start")
        # Advances on every call that generates LHS samples without an
        # explicit rng_key, so repeated fit() calls on the same orchestrator
        # don't silently reuse the same starting points. Guarded by a lock:
        # concurrent fit() calls on the same orchestrator would otherwise be
        # able to read-then-increment the same counter value and derive an
        # identical rng_key (the read-increment isn't atomic in Python).
        self._rng_call_count = 0
        self._rng_lock = threading.Lock()

    def _curve_fit_config(self) -> dict[str, Any]:
        """Extract constructor kwargs mirroring ``self.curve_fit``.

        Worker threads must build their own ``CurveFit()`` for thread
        safety (mutable per-fit state), but a caller-supplied
        ``curve_fit_instance`` should still control worker behavior
        (e.g. ``enable_stability``, ``flength``) rather than being silently
        dropped in favor of all-default construction.
        """
        cf = self.curve_fit
        return {
            "flength": cf.flength,
            "use_dynamic_sizing": cf.use_dynamic_sizing,
            "enable_stability": cf.enable_stability,
            "enable_recovery": cf.enable_recovery,
            "enable_overflow_check": cf.enable_overflow_check,
            "cache_config": cf.cache_config,
            "max_jacobian_elements_for_svd": cf.max_jacobian_elements_for_svd,
        }

    @classmethod
    def from_preset(
        cls,
        preset_name: str,
        curve_fit_instance: "CurveFit | None" = None,
    ) -> "MultiStartOrchestrator":
        """Create orchestrator from a named preset.

        Parameters
        ----------
        preset_name : str
            Name of the preset. One of: 'fast', 'robust', 'global',
            'thorough', 'streaming'.
        curve_fit_instance : CurveFit, optional
            Custom CurveFit instance for optimization.

        Returns
        -------
        MultiStartOrchestrator
            Orchestrator instance configured with preset values.

        Raises
        ------
        ValueError
            If preset_name is not a known preset.

        Examples
        --------
        >>> orchestrator = MultiStartOrchestrator.from_preset('robust')
        >>> print(orchestrator.config.n_starts)
        5
        """
        config = GlobalOptimizationConfig.from_preset(preset_name)
        return cls(config=config, curve_fit_instance=curve_fit_instance)

    def _generate_starting_points(
        self,
        n_params: int,
        lb: np.ndarray,
        ub: np.ndarray,
        p0: np.ndarray | None = None,
        rng_key: Any = None,
    ) -> np.ndarray:
        """Generate starting points using the configured sampler.

        Parameters
        ----------
        n_params : int
            Number of parameters.
        lb : np.ndarray
            Lower bounds for parameters.
        ub : np.ndarray
            Upper bounds for parameters.
        p0 : np.ndarray, optional
            Center point for centering samples (if center_on_p0=True).
        rng_key : Any, optional
            JAX random key for reproducibility.

        Returns
        -------
        np.ndarray
            Array of shape (n_starts, n_params) with starting points.
        """
        n_starts = self.config.n_starts

        if n_starts <= 0:
            return np.array([]).reshape(0, n_params)

        # Get sampler function
        sampler_name = self.config.sampler
        if sampler_name == "sobol" and n_params > 21:
            warnings.warn(
                f"Sobol sampling supports at most 21 dimensions (got {n_params}); "
                "falling back to Latin hypercube sampling.",
                stacklevel=2,
            )
            sampler_name = "lhs"
        elif sampler_name == "halton" and n_params > _HALTON_MAX_DIMS:
            warnings.warn(
                f"Halton sampling supports at most {_HALTON_MAX_DIMS} dimensions "
                f"(got {n_params}); falling back to Latin hypercube sampling.",
                stacklevel=2,
            )
            sampler_name = "lhs"
        sampler = get_sampler(sampler_name)

        # Generate samples in [0, 1]^n
        if sampler_name == "lhs":
            # Base key is fixed (PRNGKey(0)) and not user-configurable: GlobalOptimizationConfig
            # has no seed field; a per-call counter is folded in below, so repeated
            # fit() calls differ but a fresh orchestrator reproduces the same sequence.
            # LHS accepts rng_key. If the caller didn't supply one, advance
            # a per-orchestrator counter so successive fit() calls don't
            # silently reuse the exact same starting points.
            if rng_key is None:
                with self._rng_lock:
                    call_count = self._rng_call_count
                    self._rng_call_count += 1
                rng_key = jax.random.fold_in(jax.random.PRNGKey(0), call_count)
            samples_raw = sampler(n_starts, n_params, rng_key=rng_key)
        else:
            # Sobol and Halton are deterministic
            samples_raw = sampler(n_starts, n_params)

        # Scale to bounds
        if self.config.center_on_p0 and p0 is not None:
            # Center samples around p0
            import jax.numpy as jnp

            samples_jnp = jnp.asarray(samples_raw)
            p0_jnp = jnp.asarray(p0)
            lb_jnp = jnp.asarray(lb)
            ub_jnp = jnp.asarray(ub)

            scaled = center_samples_around_p0(
                samples_jnp,
                p0_jnp,
                self.config.scale_factor,
                lb_jnp,
                ub_jnp,
            )
            return np.asarray(scaled)
        # Scale to full bounds
        import jax.numpy as jnp

        samples_jnp = jnp.asarray(samples_raw)
        lb_jnp = jnp.asarray(lb)
        ub_jnp = jnp.asarray(ub)

        scaled = scale_samples_to_bounds(samples_jnp, lb_jnp, ub_jnp)
        return np.asarray(scaled)

    def evaluate_starting_points(
        self,
        f: Callable,
        xdata: np.ndarray,
        ydata: np.ndarray,
        starting_points: np.ndarray,
        bounds: tuple[np.ndarray, np.ndarray],
        **kwargs: Any,
    ) -> tuple[
        list[tuple[np.ndarray, float, CurveFitResult | None]],
        dict[str, Any],
    ]:
        """Evaluate starting points in parallel using ThreadPoolExecutor.

        Each starting point is evaluated with an isolated CurveFit instance
        to avoid thread-safety issues with mutable per-fit state in
        LeastSquares. JIT-compiled functions and the compilation cache are
        shared safely across threads.

        Parameters
        ----------
        f : Callable
            Model function ``f(x, *params) -> y``.
        xdata : np.ndarray
            Independent variable data.
        ydata : np.ndarray
            Dependent variable data.
        starting_points : np.ndarray
            Array of shape (n_starts, n_params) with starting points.
        bounds : tuple
            Tuple of (lower_bounds, upper_bounds) for parameters.
        **kwargs
            Additional arguments passed to curve_fit.

        Returns
        -------
        results : list[tuple[np.ndarray, float, CurveFitResult | None]]
            List of (params, loss, result) tuples sorted by loss (ascending).
        diagnostics : dict[str, Any]
            Parallel diagnostics with keys ``parallel``, ``n_workers``,
            ``wall_time_sec``.
        """
        if len(starting_points) == 0:
            return [], {"parallel": False, "n_workers": 0, "wall_time_sec": 0.0}

        import time as _time
        from concurrent.futures import ThreadPoolExecutor, as_completed

        n_starts = len(starting_points)
        n_workers = _select_worker_count(n_starts)

        self.logger.debug(
            f"Evaluating {n_starts} starting points with {n_workers} workers",
            n_starts=n_starts,
            n_workers=n_workers,
        )

        start_wall = _time.monotonic()
        results: list[tuple[np.ndarray, float, CurveFitResult | None]] = [
            None,  # type: ignore[list-item]
        ] * n_starts
        curve_fit_kwargs = self._curve_fit_config()
        callback_shared_warned = False

        def start_kwargs() -> dict:
            # A stateful callback (e.g. EarlyStopping) must not be shared across
            # starts/threads, so each start gets its own deep copy.
            nonlocal callback_shared_warned
            out = kwargs.copy()
            if out.get("callback") is not None:
                try:
                    out["callback"] = copy.deepcopy(out["callback"])
                except Exception as e:
                    if not callback_shared_warned:
                        callback_shared_warned = True
                        self.logger.warning(
                            f"Callback could not be deep-copied ({e}); sharing one "
                            "instance across starts, which may give run-to-run "
                            "variation if it is stateful",
                        )
            return out

        # Per-start non-convergence is an expected, internal outcome of multi-start
        # search: many starts are deliberately spread across the basin and the
        # orchestrator aggregates them, reporting the best result (and its own status
        # if every start fails). Suppress the per-start OptimizeWarning here so it
        # does not surface to the user once per failed start. The filter is set on
        # the main thread before any worker thread is spawned and held until the pool
        # has fully joined. It is refcounted (not catch_warnings) so overlapping
        # multi-start calls from different user threads cannot leak the filter.
        start_logs: list[list[logging.LogRecord]] = [[] for _ in range(n_starts)]
        _install_defer_filter()
        with _suppress_optimize_warning():
            if n_workers <= 1:
                # Sequential fallback (1 start or 1 worker)
                for i, p0 in enumerate(starting_points):
                    results[i] = _fit_start_quietly(
                        start_logs[i],
                        f,
                        xdata,
                        ydata,
                        p0,
                        bounds,
                        start_kwargs(),
                        curve_fit_kwargs,
                    )
                    _params, loss, _ = results[i]
                    self.logger.debug(
                        f"Starting point {i + 1}/{n_starts}: loss={loss:.6f}",
                        starting_point_idx=i,
                        loss=loss,
                    )
            else:
                # Parallel execution
                futures = {}
                with ThreadPoolExecutor(max_workers=n_workers) as executor:
                    for i, p0 in enumerate(starting_points):
                        future = executor.submit(
                            _fit_start_quietly,
                            start_logs[i],
                            f,
                            xdata,
                            ydata,
                            p0,
                            bounds,
                            start_kwargs(),
                            curve_fit_kwargs,
                        )
                        futures[future] = i

                    for future in as_completed(futures):
                        i = futures[future]
                        results[i] = future.result()
                        _params, loss, _ = results[i]
                        self.logger.debug(
                            f"Starting point {i + 1}/{n_starts}: loss={loss:.6f}",
                            starting_point_idx=i,
                            loss=loss,
                        )

        wall_time = _time.monotonic() - start_wall

        parallel_diagnostics: dict[str, Any] = {
            "parallel": n_workers > 1,
            "n_workers": n_workers,
            "wall_time_sec": wall_time,
        }

        # Re-log only the winner's deferred warnings (stable sort: first min wins).
        best_i = min(range(n_starts), key=lambda i: results[i][1])
        for record in start_logs[best_i]:
            record._nlsq_replay = True  # type: ignore[attr-defined]
            logging.getLogger(record.name).handle(record)

        # Sort by loss (ascending)
        results.sort(key=lambda x: x[1])

        # The per-start OptimizeWarning suppression above is scoped to
        # "expected, internal" non-convergence noise from the N-1 losing
        # starts -- it must not also swallow a genuine warning that applies
        # to the WINNING start, since that's the result actually returned
        # to the caller. Re-derive (outside the ignore filter, so it's no
        # longer suppressed) whether the winner's covariance could not be
        # estimated -- the same all-inf-pcov condition _compute_covariance
        # uses to decide warn_cov -- and re-raise it if so.
        if results:
            _best_params, _best_loss, best_result = results[0]
            best_pcov = getattr(best_result, "pcov", None)
            if not getattr(best_result, "success", True):
                warnings.warn(
                    "Optimal parameters not found: "
                    f"{getattr(best_result, 'message', 'did not converge')}",
                    OptimizeWarning,
                    stacklevel=2,
                )
            if best_pcov is not None and np.all(np.isinf(np.asarray(best_pcov))):
                warnings.warn(
                    "Covariance of the parameters could not be estimated",
                    OptimizeWarning,
                    stacklevel=2,
                )

        return results, parallel_diagnostics

    def fit(
        self,
        f: Callable,
        xdata: np.ndarray,
        ydata: np.ndarray,
        p0: np.ndarray | None = None,
        bounds: tuple | None = None,
        **kwargs: Any,
    ) -> CurveFitResult:
        """Run multi-start optimization and return best result.

        This is the main entry point for multi-start optimization. It:

        1. Infers bounds if not provided
        2. Estimates p0 if not provided and center_on_p0=True
        3. Generates LHS starting points; a user-supplied ``p0`` (clipped to the
           bounds) takes the first of the ``n_starts`` slots, so the result is never
           worse than a single start from ``p0``
        4. Evaluates all starting points
        5. Returns the result with the minimum loss

        Parameters
        ----------
        f : Callable
            Model function ``f(x, *params) -> y``.
        xdata : np.ndarray
            Independent variable data.
        ydata : np.ndarray
            Dependent variable data.
        p0 : np.ndarray, optional
            Initial parameter guess. Used for centering if center_on_p0=True.
        bounds : tuple, optional
            Tuple of (lower_bounds, upper_bounds) for parameters. If None,
            bounds are inferred from data.
        kwargs : dict
            Additional arguments passed to curve_fit.

        Returns
        -------
        CurveFitResult
            Best optimization result with multi-start diagnostics.

        Examples
        --------
        >>> orchestrator = MultiStartOrchestrator.from_preset('robust')
        >>> result = orchestrator.fit(model, x, y, bounds=([0, 0], [10, 10]))
        >>> print(f"Best params: {result.popt}")
        >>> print(f"Multi-start diagnostics: {result.multistart_diagnostics}")
        """
        xdata = np.asarray(xdata)
        ydata = np.asarray(ydata)

        # timeit/return_eval/full_output make curve_fit return a plain tuple, which
        # carries neither cost nor diagnostics. Run the search with CurveFitResult
        # objects and apply the mode only to the final refit of the winner.
        tuple_modes = {
            k: kwargs.pop(k)
            for k in ("full_output", "return_eval", "timeit")
            if kwargs.get(k)
        }

        # Diagnostics tracking
        diagnostics: dict[str, Any] = {
            "n_starts_configured": self.config.n_starts,
            "sampler": self.config.sampler,
            "center_on_p0": self.config.center_on_p0,
            "scale_factor": self.config.scale_factor,
            "bounds_inferred": False,
            "p0_estimated": False,
            "bypassed": False,
        }

        # Check if multi-start is disabled (n_starts=0)
        if self.config.n_starts == 0:
            self.logger.debug("Multi-start disabled (n_starts=0), using single-start")
            diagnostics["bypassed"] = True
            diagnostics["n_starts_evaluated"] = 0

            # Run single-start optimization
            result: CurveFitResult = self.curve_fit.curve_fit(  # type: ignore[assignment]
                f,
                xdata,
                ydata,
                p0=p0,
                bounds=bounds or (-np.inf, np.inf),
                **kwargs,
                **tuple_modes,
            )
            if isinstance(result, tuple):
                return result  # type: ignore[return-value]

            # Add diagnostics to result
            result["multistart_diagnostics"] = diagnostics
            return result

        # Rows with NaN/Inf (dropped later by nan_policy='omit') must not reach the
        # p0 / bounds heuristics, which would return NaN for them.
        x_fin, y_fin = finite_rows(xdata, ydata)

        # Determine number of parameters
        user_p0_given = p0 is not None
        if p0 is not None:
            p0 = np.atleast_1d(p0)
            n_params = len(p0)
        else:
            # Try to estimate p0 for parameter count
            try:
                p0_estimated = estimate_initial_parameters(f, x_fin, y_fin, p0="auto")
                p0 = np.atleast_1d(p0_estimated)
                n_params = len(p0)
                diagnostics["p0_estimated"] = True
                self.logger.debug(
                    f"Estimated initial parameters: {p0}",
                    p0=p0.tolist(),
                )
            except Exception as e:
                # Fall back to signature inspection
                from nlsq.streaming.strategy import default_p0

                p0 = default_p0(f)
                n_params = len(p0)
                self.logger.debug(
                    f"Could not estimate p0, using defaults: {e}",
                    n_params=n_params,
                )

        # Handle bounds
        fit_bounds: Any  # (-inf, inf) scalars or (lb, ub) arrays, as curve_fit accepts
        if bounds is None:
            # Infer bounds for multi-start
            self.logger.debug("Inferring bounds for multi-start sampling")
            lb, ub = infer_bounds_for_multistart(x_fin, y_fin, p0)
            # Inferred bounds only shape the sampling box; fits stay unbounded.
            fit_bounds = (-np.inf, np.inf)
            diagnostics["bounds_inferred"] = True
            diagnostics["inferred_bounds"] = {
                "lower": lb.tolist(),
                "upper": ub.tolist(),
            }
        else:
            # Convert bounds to arrays
            lb = np.atleast_1d(bounds[0])
            ub = np.atleast_1d(bounds[1])

            # Broadcast scalar bounds
            if len(lb) == 1:
                lb = np.full(n_params, lb[0])
            if len(ub) == 1:
                ub = np.full(n_params, ub[0])

            if len(lb) != n_params or len(ub) != n_params:
                raise ValueError(
                    f"bounds have {len(lb)} lower / {len(ub)} upper entries but "
                    f"p0 has {n_params} parameters"
                )

            # The user's bounds (possibly infinite) constrain every actual fit.
            fit_bounds = (lb, ub)

            # Check for infinite bounds and infer if needed
            if not np.all(np.isfinite(lb)) or not np.all(np.isfinite(ub)):
                self.logger.debug("Some bounds are infinite, inferring finite bounds")
                lb_inferred, ub_inferred = infer_bounds_for_multistart(
                    x_fin,
                    y_fin,
                    p0,
                    user_bounds=(lb, ub),
                )
                lb = lb_inferred
                ub = ub_inferred
                diagnostics["bounds_inferred"] = True

        # Generate starting points
        self.logger.info(
            f"Generating {self.config.n_starts} starting points using {self.config.sampler}",
            n_starts=self.config.n_starts,
            sampler=self.config.sampler,
            center_on_p0=self.config.center_on_p0,
        )

        starting_points = self._generate_starting_points(
            n_params=n_params,
            lb=lb,
            ub=ub,
            p0=p0 if self.config.center_on_p0 else None,
        )

        # The user's own p0 is always evaluated, so multi-start can never end worse
        # than a single start. It takes one of the n_starts slots (the first, so it
        # also wins ties); n_starts=1 therefore reduces to the single start.
        diagnostics["p0_included"] = bool(user_p0_given and len(starting_points) > 0)
        if diagnostics["p0_included"]:
            p0_start = np.clip(np.asarray(p0, dtype=float), *fit_bounds)
            starting_points = np.vstack([p0_start[None, :], starting_points[:-1]])

        diagnostics["n_starts_generated"] = len(starting_points)

        # Evaluate all starting points
        self.logger.info(f"Evaluating {len(starting_points)} starting points")
        evaluation_results, parallel_diag = self.evaluate_starting_points(
            f=f,
            xdata=xdata,
            ydata=ydata,
            starting_points=starting_points,
            bounds=fit_bounds,
            **kwargs,
        )

        # Merge parallel diagnostics
        diagnostics.update(parallel_diag)

        # Count successful evaluations
        n_successful = sum(
            1 for _, loss, _ in evaluation_results if loss < float("inf")
        )
        diagnostics["n_starts_evaluated"] = len(evaluation_results)
        diagnostics["n_starts_successful"] = n_successful

        # Select best result
        if n_successful == 0:
            self.logger.warning(
                "All starting points failed, falling back to single-start",
            )
            # Fall back to single-start with original p0
            result = self.curve_fit.curve_fit(  # type: ignore[assignment]
                f,
                xdata,
                ydata,
                p0=p0,
                bounds=fit_bounds,
                **kwargs,
            )
            diagnostics["fallback_to_single_start"] = True
        else:
            # Get best result (first in sorted list with finite loss)
            best_params, best_loss, best_result = evaluation_results[0]

            self.logger.info(
                f"Best starting point: loss={best_loss:.6f}",
                best_loss=best_loss,
                best_params=best_params.tolist()
                if hasattr(best_params, "tolist")
                else list(best_params),
            )

            diagnostics["best_loss"] = best_loss
            diagnostics["all_losses"] = [
                loss for _, loss, _ in evaluation_results if loss < float("inf")
            ]

            if best_result is not None:
                result = best_result
            else:
                # Shouldn't happen, but fallback
                result = self.curve_fit.curve_fit(  # type: ignore[assignment]
                    f,
                    xdata,
                    ydata,
                    p0=best_params,
                    bounds=fit_bounds,
                    **kwargs,
                )

        # Add diagnostics to result
        result["multistart_diagnostics"] = diagnostics

        # Also add as attribute for convenience
        if not hasattr(result, "multistart_diagnostics"):
            result.multistart_diagnostics = diagnostics  # type: ignore[attr-defined]

        if tuple_modes:
            # Refit once from the winner (already converged) in the requested mode.
            return self.curve_fit.curve_fit(  # type: ignore[return-value]
                f,
                xdata,
                ydata,
                p0=np.asarray(result.popt),
                bounds=fit_bounds,
                **kwargs,
                **tuple_modes,
            )

        return result
